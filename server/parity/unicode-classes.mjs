#!/usr/bin/env node
// Rewrites src/routes/unicode_classes.rs: the code points two regexes of the
// TypeScript match, as V8 decides them, so the Rust reads the same Unicode
// version Next does instead of a crate's.
//
//   TITLE_KEY_DROP  /[\s\p{P}\p{S}_]/u   memeTitleKey (scripts/meme-title-key.mjs)
//   WORD            /[\p{Script=Hangul}\p{L}\p{N}]/u   normalizeKoreanText (lib/mpe/candidates.ts)
//   LETTER_OR_NUMBER  /[\p{L}\p{N}]/u   the MCP corpus search (integrations/memecatch-chatgpt/src/corpus.mjs)
//
// Run it with the Node of the Next image (22) after a Node upgrade there:
//
//   node server/parity/unicode-classes.mjs > server/src/routes/unicode_classes.rs
if (!process.version.startsWith("v22.")) {
  console.error(`run this with Node 22, the Next image's (this is ${process.version})`);
  process.exit(2);
}

function ranges(pattern) {
  const out = [];
  for (let point = 0; point <= 0x10ffff; point += 1) {
    if (point >= 0xd800 && point <= 0xdfff) continue;
    if (!pattern.test(String.fromCodePoint(point))) continue;
    const last = out.at(-1);
    if (last && last[1] === point - 1) last[1] = point;
    else out.push([point, point]);
  }
  return out;
}

const table = (name, doc, pattern) => {
  const pairs = ranges(pattern).map(([from, to]) => `(0x${from.toString(16)}, 0x${to.toString(16)}),`);
  const lines = [];
  for (let at = 0; at < pairs.length; at += 5) lines.push(`    ${pairs.slice(at, at + 5).join(" ")}`);
  return `/// ${doc}\n#[rustfmt::skip]\npub const ${name}: [(u32, u32); ${pairs.length}] = [\n${lines.join("\n")}\n];\n`;
};

process.stdout.write(`//! Generated by \`parity/unicode-classes.mjs\` on Node ${process.version} (Unicode
//! ${process.versions.unicode}). Do not edit: run the script again.

/// Whether \`point\` lies in one of the sorted, disjoint \`ranges\`.
pub fn contains(ranges: &[(u32, u32)], point: char) -> bool {
    let point = u32::from(point);
    ranges
        .binary_search_by(|&(from, to)| {
            if to < point {
                std::cmp::Ordering::Less
            } else if from > point {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

${table("TITLE_KEY_DROP", "`/[\\s\\p{P}\\p{S}_]/u` of `memeTitleKey`.", /[\s\p{P}\p{S}_]/u)}
${table("WORD", "`/[\\p{Script=Hangul}\\p{L}\\p{N}]/u` of `normalizeKoreanText`.", /[\p{Script=Hangul}\p{L}\p{N}]/u)}
${table("LETTER_OR_NUMBER", "`/[\\p{L}\\p{N}]/u` of the MCP corpus search.", /[\p{L}\p{N}]/u)}`);
