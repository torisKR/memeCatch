#!/bin/bash
# Runs migrate-from-supabase.sh against local fixture databases.
# Covers a seeded target, a row-count mismatch, and a restore error.
# Uses the host network so the client can reach Postgres without a bridge route.
# Does not contact Supabase.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
server="memecatch-migrate-pg"
image="memecatch-pgtools:ci"
password="postgres"
port="55432"

docker rm -f "$server" >/dev/null 2>&1 || true
trap 'docker rm -f "$server" >/dev/null 2>&1 || true' EXIT

docker build -t "$image" - <<'EOF'
FROM postgres:16
RUN apt-get update \
  && apt-get install -y --no-install-recommends python3 \
  && rm -rf /var/lib/apt/lists/*
EOF

docker run -d --name "$server" --network host \
  -e POSTGRES_PASSWORD="$password" "$image" postgres -c port="$port" >/dev/null
# pg_isready turns true while the entrypoint is still restarting. The next
# check then exits 2. Wait until the server accepts a query.
ready=0
for _ in $(seq 1 90); do
  if docker exec "$server" psql -v ON_ERROR_STOP=1 --username postgres --dbname postgres -p "$port" -c "select 1" >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 1
done
if [[ "$ready" -ne 1 ]]; then
  echo "postgres did not accept a query" >&2
  docker logs "$server" >&2 || true
  exit 1
fi

filtered="$(awk -f "$root/scripts/postgres/filter-pg17-dump.awk" <<'EOF'
SET transaction_timeout = 0;
SELECT pg_catalog.set_config('transaction_timeout', '0', false);
SET session_replication_role = origin;
COPY public.memes (title) FROM stdin;
SET transaction_timeout = 0;
\.
SELECT 1;
EOF
)"
timeout_lines="$(printf '%s\n' "$filtered" | grep -c '^SET transaction_timeout = 0;$' || true)"
if [[ "$timeout_lines" != "1" || "$filtered" == *"set_config"* || "$filtered" == *"session_replication_role"* ]]; then
  echo "memecatch migrate test: PG17 settings were not filtered" >&2
  printf '%s\n' "$filtered" >&2
  exit 1
fi
if ! printf '%s\n' "$filtered" | awk 'BEGIN { copy = 0 } /^COPY / { copy = 1 } /^\\\.$/ { copy = 0 } /^SET transaction_timeout = 0;$/ { if (copy != 1) bad = 1 } END { exit bad }'; then
  echo "memecatch migrate test: transaction_timeout survived outside COPY data" >&2
  exit 1
fi
psql_exec() {
  docker exec -i "$server" psql -U postgres -p "$port" -v ON_ERROR_STOP=1 "$@"
}

base_schema() {
  local database="$1"
  psql_exec -d "$database" <<'SQL'
CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE IF NOT EXISTS auth.users (
  id uuid PRIMARY KEY,
  email text,
  encrypted_password text,
  email_confirmed_at timestamptz,
  raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.memes (
  id uuid PRIMARY KEY,
  title text
);
CREATE TABLE IF NOT EXISTS public.tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY
);
SQL
}

seed_target() {
  local database="$1"
  psql_exec -d "$database" <<'SQL'
INSERT INTO public.memes (id, title)
SELECT ('10000000-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid, 'seed ' || n
  FROM generate_series(1, 5) AS n;
INSERT INTO public.tags (name)
SELECT 'seed-tag-' || n FROM generate_series(1, 17) AS n;
SQL
}

run_migration() {
  local source_db="$1"
  local target_db="$2"
  local envfile
  envfile="$(mktemp)"
  chmod 600 "$envfile"
  cat > "$envfile" <<EOF
MEMECATCH_ALLOW_SUPABASE_DUMP=owner-approved
SUPABASE_DB_URL=postgresql://postgres:${password}@127.0.0.1:${port}/${source_db}
DATABASE_URL=postgresql://postgres:${password}@127.0.0.1:${port}/${target_db}
EOF
  set +e
  docker run --rm --network host \
    -v "$root:/work" -w /work \
    --env-file "$envfile" \
    --entrypoint bash "$image" scripts/postgres/migrate-from-supabase.sh
  local status=$?
  set -e
  rm -f "$envfile"
  return "$status"
}

count_of() {
  local database="$1"
  local query="$2"
  docker exec "$server" psql -U postgres -p "$port" -d "$database" -At -c "$query"
}

psql_exec -d postgres <<'SQL'
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'memecatch') THEN
    CREATE ROLE memecatch NOLOGIN;
  END IF;
END $$;
SQL

echo "memecatch migrate test: success path"
psql_exec -c "DROP DATABASE IF EXISTS fixture_source;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_premigrate;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_import;"
psql_exec -c "CREATE DATABASE fixture_source;"
psql_exec -c "CREATE DATABASE memecatch;"
base_schema fixture_source
base_schema memecatch
seed_target memecatch
psql_exec -d fixture_source <<'SQL'
INSERT INTO public.memes (id, title) VALUES
  ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaa1', 'alpha'),
  ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaa2', 'beta');
INSERT INTO public.tags (name) VALUES ('one'), ('two'), ('three');
INSERT INTO auth.users (id, email, encrypted_password, email_confirmed_at, raw_user_meta_data)
VALUES (
  'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbb1',
  'migrated@example.com',
  '$2b$10$abcdefghijklmnopqrstuu',
  now(),
  '{"nickname":"밈러"}'::jsonb
);
SQL
for database in fixture_source memecatch; do
  psql_exec -d "$database" <<'SQL'
ALTER TABLE public.memes ADD COLUMN tag_id integer;
ALTER TABLE public.tags ADD COLUMN meme_id uuid;
ALTER TABLE public.memes
  ADD CONSTRAINT memes_tag_id_fkey FOREIGN KEY (tag_id) REFERENCES public.tags (id);
ALTER TABLE public.tags
  ADD CONSTRAINT tags_meme_id_fkey FOREIGN KEY (meme_id) REFERENCES public.memes (id);
SQL
done
psql_exec -d fixture_source <<'SQL'
UPDATE public.tags
   SET meme_id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaa1'
 WHERE name = 'one';
UPDATE public.memes
   SET tag_id = (SELECT id FROM public.tags WHERE name = 'one')
 WHERE id = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaa1';
SQL
run_migration fixture_source memecatch
[[ "$(count_of memecatch 'SELECT count(*) FROM public.memes')" == "2" ]]
[[ "$(count_of memecatch 'SELECT count(*) FROM public.tags')" == "3" ]]
[[ "$(count_of memecatch 'SELECT count(*) FROM auth.users')" == "1" ]]
[[ "$(count_of memecatch 'SELECT count(*) FROM public."user"')" == "1" ]]
[[ "$(count_of memecatch 'SELECT count(*) FROM public.account')" == "1" ]]
[[ "$(count_of memecatch "SELECT \"emailVerified\" FROM public.\"user\"")" == "t" ]]
[[ "$(count_of memecatch "SELECT pg_get_userbyid(c.relowner) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relname = 'user'")" == "memecatch" ]]
[[ "$(count_of memecatch_premigrate 'SELECT count(*) FROM public.memes')" == "5" ]]
[[ "$(count_of memecatch_premigrate 'SELECT count(*) FROM public.tags')" == "17" ]]
echo "memecatch migrate test: success path kept the seeded database aside"

echo "memecatch migrate test: row-count mismatch leaves the target"
psql_exec -c "DROP DATABASE IF EXISTS fixture_mismatch;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_fail;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_fail_import;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_fail_premigrate;"
psql_exec -c "CREATE DATABASE fixture_mismatch;"
psql_exec -c "CREATE DATABASE memecatch_fail;"
base_schema fixture_mismatch
base_schema memecatch_fail
seed_target memecatch_fail
psql_exec -d memecatch_fail <<'SQL'
CREATE FUNCTION public.add_extra_tag() RETURNS boolean
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO public.tags (id, name) VALUES (1000, 'from-check')
  ON CONFLICT (id) DO NOTHING;
  RETURN true;
END $$;
ALTER TABLE public.memes ADD CONSTRAINT memes_extra CHECK (public.add_extra_tag()) NOT VALID;
SQL
psql_exec -d fixture_mismatch <<'SQL'
INSERT INTO public.memes (id, title) VALUES ('cccccccc-cccc-4ccc-8ccc-ccccccccccc1', 'only');
INSERT INTO public.tags (name) VALUES ('source-tag');
INSERT INTO auth.users (id, email, encrypted_password, raw_user_meta_data)
VALUES (
  'dddddddd-dddd-4ddd-8ddd-ddddddddddd1',
  'mismatch@example.com',
  '$2b$10$abcdefghijklmnopqrstuu',
  '{}'::jsonb
);
SQL
if run_migration fixture_mismatch memecatch_fail; then
  echo "memecatch migrate test: mismatch was accepted" >&2
  exit 1
fi
[[ "$(count_of memecatch_fail 'SELECT count(*) FROM public.memes')" == "5" ]]
[[ "$(count_of memecatch_fail 'SELECT count(*) FROM public.tags')" == "17" ]]
[[ "$(count_of postgres "SELECT count(*) FROM pg_database WHERE datname = 'memecatch_fail_import'")" == "0" ]]
[[ "$(count_of postgres "SELECT count(*) FROM pg_database WHERE datname = 'memecatch_fail_premigrate'")" == "0" ]]
echo "memecatch migrate test: mismatch left the seeded target in place"

echo "memecatch migrate test: restore error leaves the target"
psql_exec -c "DROP DATABASE IF EXISTS fixture_bad;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_bad;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_bad_import;"
psql_exec -c "DROP DATABASE IF EXISTS memecatch_bad_premigrate;"
psql_exec -c "CREATE DATABASE fixture_bad;"
psql_exec -c "CREATE DATABASE memecatch_bad;"
base_schema fixture_bad
psql_exec -d memecatch_bad <<'SQL'
CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY,
  email text,
  encrypted_password text,
  email_confirmed_at timestamptz,
  raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE TABLE public.memes (
  id uuid PRIMARY KEY,
  title text NOT NULL
);
CREATE TABLE public.tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY
);
INSERT INTO public.memes (id, title)
SELECT ('20000000-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid, 'kept ' || n
  FROM generate_series(1, 5) AS n;
INSERT INTO public.tags (name)
SELECT 'kept-tag-' || n FROM generate_series(1, 17) AS n;
SQL
psql_exec -d fixture_bad <<'SQL'
INSERT INTO public.memes (id, title) VALUES ('eeeeeeee-eeee-4eee-8eee-eeeeeeeeeee1', NULL);
INSERT INTO public.tags (name) VALUES ('bad-tag');
SQL
if run_migration fixture_bad memecatch_bad; then
  echo "memecatch migrate test: constraint failure was accepted" >&2
  exit 1
fi
[[ "$(count_of memecatch_bad 'SELECT count(*) FROM public.memes')" == "5" ]]
[[ "$(count_of memecatch_bad 'SELECT count(*) FROM public.tags')" == "17" ]]
[[ "$(count_of postgres "SELECT count(*) FROM pg_database WHERE datname = 'memecatch_bad_import'")" == "0" ]]
[[ "$(count_of postgres "SELECT count(*) FROM pg_database WHERE datname = 'memecatch_bad_premigrate'")" == "0" ]]
echo "memecatch migrate test: restore error left the seeded target in place"
