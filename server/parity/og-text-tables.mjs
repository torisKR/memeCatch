#!/usr/bin/env node
// Writes server/src/og/satori/linebreak_data.rs from the `linebreak` package
// Satori uses (bundled in next/og): the line break class of every code point
// as its class trie gives it, and the pair table. See README.md in this
// directory, "Open Graph images".
//
//   node server/parity/og-text-tables.mjs
//
// It also writes server/tests/fixtures/og/segments.json: for a corpus of
// card texts, the graphemes and words Node's Intl.Segmenter gives and the
// line break words of `linebreak`, which tests/og_text.rs holds the Rust to.
import { cpSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ogFile = realpathSync(join(root, "node_modules/next/dist/compiled/@vercel/og/index.node.js"));
const scratch = mkdtempSync(join(tmpdir(), "og-text-tables-"));
cpSync(dirname(ogFile), scratch, { recursive: true });
const bundle = join(scratch, "index.node.js");
const exported = readFileSync(bundle, "utf8").replace(
  "export {\n  ImageResponse,",
  "export {\n  $557adaaeb0c7885f$var$classTrie as __classTrie, $32627af916ac1b00$export$5bdb8ccbf5c57afc as __pairs, $557adaaeb0c7885f$exports as __LineBreaker, ImageResponse,",
);
if (!exported.includes("__classTrie")) throw new Error("the next/og bundle changed shape");
writeFileSync(bundle, exported);
const { __classTrie: trie, __pairs: pairs, __LineBreaker: LineBreaker } = await import(pathToFileURL(bundle).href);
rmSync(scratch, { recursive: true, force: true });

const runs = [];
for (let cp = 0; cp <= 0x10ffff; cp += 1) {
  const value = trie.get(cp);
  const last = runs[runs.length - 1];
  if (last && last[2] === value && last[1] === cp - 1) last[1] = cp;
  else runs.push([cp, cp, value]);
}
const hex = (n) => `0x${n.toString(16)}`;
const lines = [];
for (let i = 0; i < runs.length; i += 4) {
  lines.push(`    ${runs.slice(i, i + 4).map(([a, b, c]) => `(${hex(a)}, ${hex(b)}, ${c})`).join(", ")},`);
}
const table = pairs.map((row) => `    [${row.join(", ")}],`).join("\n");
const source = `//! Generated by \`parity/og-text-tables.mjs\` from the \`linebreak\` package
//! bundled in next/og. Do not edit: run the script again.

/// \`classTrie.get(codePoint)\` as runs \`(first, last, class)\`, sorted.
#[rustfmt::skip]
pub static CLASSES: [(u32, u32, u8); ${runs.length}] = [
${lines.join("\n")}
];

/// \`pairTable[current][next]\`.
#[rustfmt::skip]
pub static PAIRS: [[u8; ${pairs[0].length}]; ${pairs.length}] = [
${table}
];
`;
writeFileSync(join(root, "server/src/og/satori/linebreak_data.rs"), source);

// The corpus: what card titles and summaries hold.
const corpus = [
  "중요한 건 꺾이지 않는 마음 (중꺾마)",
  "폼 미쳤다",
  "너 뭐 돼?",
  "히딩크 '나는 아직 배가 고프다'",
  "Korean Memes Explained",
  "韓国ミームをわかりやすく解説",
  "看懂韩国网络迷因，真的。",
  "밈 😂🔥 테스트",
  "👨‍👩‍👧‍👦 가족 🇰🇷 국기 ❤️ 하트 👍🏽",
  "a b c 밈 캐치",
  "éte 한글가 조합",
  "(괄호) [대괄호] {중괄호} “따옴표” ‘작은’ — 대시 – 반대시",
  "100% 2024년 1,000원 3.14 v2.0",
  "https://catchmeme.com/memes/abc",
  "well-known co-op e-mail",
  "ㅋㅋㅋㅋ ㅎㅎ ㅠㅠ",
  "...!!!???~~~",
  "  앞뒤 공백  ",
  "Ｆｕｌｌ ｗｉｄｔｈ ＡＢＣ",
  "タイ語 ภาษาไทย عربى",
  "zero​width‍join",
  "( 열린 괄호 뒤 공백",
  "«guillemets» ¿Qué? ¡Sí!",
  "✕ ● ▲ ◌",
];
const graphemes = new Intl.Segmenter(undefined, { granularity: "grapheme" });
const words = new Intl.Segmenter(undefined, { granularity: "word" });
const breakWords = (text) => {
  const breaker = new LineBreaker(text);
  const out = [];
  let last = 0;
  for (let bk = breaker.nextBreak(); bk; bk = breaker.nextBreak()) {
    out.push([text.slice(last, bk.position), bk.required]);
    last = bk.position;
  }
  return out;
};
const cases = corpus.map((text) => ({
  text,
  graphemes: [...graphemes.segment(text)].map((s) => s.segment),
  words: [...words.segment(text)].map((s) => s.segment),
  lineWords: breakWords(text),
}));
writeFileSync(join(root, "server/tests/fixtures/og/segments.json"), `${JSON.stringify({ node: process.version, unicode: process.versions.unicode, cases }, null, 1)}\n`);
console.log(`${runs.length} class runs, ${cases.length} corpus texts`);
